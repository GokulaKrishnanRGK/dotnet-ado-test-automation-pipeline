            'Service request created.'
        );
    END;
    $$;

    CREATE OR REPLACE FUNCTION opsledger_assign_service_request(
        p_id TEXT,
        p_assignee_name TEXT,
        p_changed_at TIMESTAMPTZ
    )
    RETURNS VOID
    LANGUAGE plpgsql
    AS $$
    BEGIN
        UPDATE service_requests
        SET
            assignee_name = p_assignee_name,
            status = 'InProgress'
        WHERE id = p_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Service request % was not found.', p_id;
        END IF;

        INSERT INTO service_request_activity (
            service_request_id,
            type,
            occurred_at,
            description
        )
        VALUES (
            p_id,
            'Assigned',
            p_changed_at,
            'Assigned to ' || p_assignee_name || '.'
        );
    END;
    $$;

    CREATE OR REPLACE FUNCTION opsledger_resolve_service_request(
        p_id TEXT,
        p_resolution_notes TEXT,
        p_changed_at TIMESTAMPTZ
    )
    RETURNS VOID
    LANGUAGE plpgsql
    AS $$
    BEGIN
        UPDATE service_requests
        SET
            resolution_notes = p_resolution_notes,
            status = 'Resolved'
        WHERE id = p_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Service request % was not found.', p_id;
        END IF;

        INSERT INTO service_request_activity (
            service_request_id,
            type,
            occurred_at,
            description
        )
        VALUES (
            p_id,
            'Resolved',
            p_changed_at,
            'Request resolved.'
        );
    END;
    $$;

    CREATE OR REPLACE FUNCTION opsledger_add_service_request_comment(
        p_id TEXT,
        p_author_name TEXT,
        p_body TEXT,
        p_created_at TIMESTAMPTZ
    )
    RETURNS VOID
    LANGUAGE plpgsql
    AS $$
    BEGIN
        IF NOT EXISTS (
            SELECT 1
            FROM service_requests
            WHERE id = p_id
        ) THEN
            RAISE EXCEPTION 'Service request % was not found.', p_id;
        END IF;

        INSERT INTO service_request_comments (
            service_request_id,
            author_name,
            body,
            created_at
        )
        VALUES (
            p_id,
            p_author_name,
            p_body,
            p_created_at
        );

        INSERT INTO service_request_activity (
            service_request_id,
            type,
            occurred_at,
            description
        )
        VALUES (
            p_id,
            'CommentAdded',
            p_created_at,
            'Comment added by ' || p_author_name || '.'
        );
    END;
    $$;
    END IF;
