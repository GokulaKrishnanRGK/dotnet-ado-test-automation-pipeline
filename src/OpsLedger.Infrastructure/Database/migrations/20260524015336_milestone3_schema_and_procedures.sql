    )
    RETURNS VOID
    LANGUAGE plpgsql
    AS $$
    BEGIN
        INSERT INTO service_requests (
            id,
            title,
            category,
            priority,
            description,
            requester_name,
            requester_email,
            impact_details,
            status,
            created_at,
